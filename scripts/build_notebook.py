            '# ==============================================================================\n',
            'class TopKTokenSelectiveAttention(nn.Module):\n',
            '    def __init__(self, dim, num_heads=6, topk_ratio=0.75):\n',
            '        super().__init__()\n',
            '        self.num_heads = num_heads\n',
            '        self.head_dim = dim // num_heads\n',
            '        self.scale = self.head_dim ** -0.5\n',
            '        self.topk_ratio = topk_ratio\n',
            '        self.qkv = nn.Linear(dim, dim * 3)\n',
            '        self.proj = nn.Linear(dim, dim)\n',
            '    def forward(self, x):\n',
            '        B, N, C = x.shape\n',
            '        qkv = self.qkv(x).reshape(B, N, 3, self.num_heads, self.head_dim).permute(2, 0, 3, 1, 4)\n',
            '        q, k, v = qkv[0], qkv[1], qkv[2]\n',
            '        attn = (q @ k.transpose(-2, -1)) * self.scale\n',
            '        k_tokens = max(1, int(N * self.topk_ratio))\n',
            '        topk_vals, topk_idx = torch.topk(attn, k=k_tokens, dim=-1)\n',
            '        mask = torch.full_like(attn, float("-inf"))\n',
            '        mask.scatter_(-1, topk_idx, topk_vals)\n',
            '        attn = F.softmax(mask, dim=-1)\n',
            '        out = (attn @ v).transpose(1, 2).reshape(B, N, C)\n',
            '        return self.proj(out)\n',
            '\n',
            'class TTSTBlock(nn.Module):\n',
            '    def __init__(self, dim=180, num_heads=6, window_size=8, topk_ratio=0.75):\n',
            '        super().__init__()\n',
            '        self.window_size = window_size\n',
            '        self.norm1 = nn.LayerNorm(dim)\n',
            '        self.attn = TopKTokenSelectiveAttention(dim, num_heads, topk_ratio)\n',
            '        self.norm2 = nn.LayerNorm(dim)\n',
            '        self.mlp = nn.Sequential(nn.Linear(dim, dim * 2), nn.GELU(), nn.Linear(dim * 2, dim))\n',
            '        self.conv = nn.Conv2d(dim, dim, 3, 1, 1)\n',
            '    def forward(self, x):\n',
            '        B, C, H, W = x.shape\n',
            '        ws = self.window_size\n',
            '        pad_h = (ws - H % ws) % ws\n',
            '        pad_w = (ws - W % ws) % ws\n',
            '        if pad_h > 0 or pad_w > 0:\n',
            '            x = F.pad(x, (0, pad_w, 0, pad_h), mode="reflect")\n',
            '        _, _, H_pad, W_pad = x.shape\n',
            '        x_win = x.view(B, C, H_pad // ws, ws, W_pad // ws, ws).permute(0, 2, 4, 3, 5, 1).contiguous().view(-1, ws * ws, C)\n',
            '        x_win = x_win + self.attn(self.norm1(x_win))\n',
            '        x_win = x_win + self.mlp(self.norm2(x_win))\n',
            '        x_out = x_win.view(B, H_pad // ws, W_pad // ws, ws, ws, C).permute(0, 5, 1, 3, 2, 4).contiguous().view(B, C, H_pad, W_pad)\n',
            '        if pad_h > 0 or pad_w > 0:\n',
            '            x_out = x_out[:, :, :H, :W]\n',
            '        return x[:, :, :H, :W] + self.conv(x_out)\n',
